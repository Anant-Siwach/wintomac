"""Assemble tests/jit/jit_hot.s (mingw binutils) and write tests/src/jit_hot_code.h: the machine code as a byte
array plus OFF_<function> offsets. Run from the repository root: python3 tests/jit/gen_code.py"""
import os, subprocess, sys, tempfile

src = "tests/jit/jit_hot.s"
out = "tests/src/jit_hot_code.h"
with tempfile.TemporaryDirectory() as d:
    obj, binf = os.path.join(d, "a.o"), os.path.join(d, "a.bin")
    subprocess.check_call(["x86_64-w64-mingw32-as", "-o", obj, src])
    subprocess.check_call(["x86_64-w64-mingw32-objcopy", "-O", "binary", "-j", ".text", obj, binf])
    code = open(binf, "rb").read()
    syms = {}
    for line in subprocess.check_output(["x86_64-w64-mingw32-nm", obj], text=True).splitlines():
        p = line.split()
        if len(p) == 3 and p[1] in "Tt" and not p[2].startswith("."):
            syms[p[2]] = int(p[0], 16)
with open(out, "w") as f:
    f.write("// Generated by tests/jit/gen_code.py from tests/jit/jit_hot.s -- do not edit.\n")
    f.write("static const unsigned char jit_hot_code[] = {\n")
    for i in range(0, len(code), 16):
        f.write("    " + ", ".join("0x%02x" % b for b in code[i:i + 16]) + ",\n")
    f.write("};\n")
    for name, off in sorted(syms.items(), key=lambda kv: kv[1]):
        if name[0].isalpha():
            f.write("#define OFF_%s 0x%x\n" % (name.upper(), off))
print("wrote %s: %d bytes, %d symbols" % (out, len(code), len(syms)))
