#!/bin/sh
# tests/shaders/tables/tables.hlsl -> tests/shaders/dx12_tables_blobs.h (checked in): SM 5.0 DXBC from vkd3d-compiler
# (fxc's role) and SM 6.0 DXIL from DXC (tools/build_dxc.sh). Used by tests/src/dx12_tables.c.
set -e
ROOT=$(cd "$(dirname "$0")/../.." && pwd)
V=$ROOT/third_party/vkd3d/install; DXC=$ROOT/third_party/dxc/build/bin/dxc
S=$ROOT/tests/shaders/tables/tables.hlsl; T=$(mktemp -d)
for st in vs ps; do
  DYLD_LIBRARY_PATH=$V/lib $V/bin/vkd3d-compiler -x hlsl -b dxbc-tpf -p ${st}_5_0 -e ${st}_main -o $T/${st}.dxbc $S
  $DXC -nologo -T ${st}_6_0 -E ${st}_main -Fo $T/${st}.dxil $S
done
{
  echo "// Generated by tools/d3d12mtl/gen_tables_blobs.sh from tests/shaders/tables/tables.hlsl. Do not edit."
  echo "#pragma once"
  for f in vs.dxbc ps.dxbc vs.dxil ps.dxil; do
    n=tables_$(echo $f | tr . _)
    echo "static const unsigned char $n[] = {"
    xxd -i < $T/$f
    echo "};"
  done
} > $ROOT/tests/shaders/dx12_tables_blobs.h
rm -rf $T
echo "[tables] -> tests/shaders/dx12_tables_blobs.h"
