#!/usr/bin/env python3
"""Generate Win64-ABI -> host OpenGL thunks from the Khronos registry (gl.xml).

Output: runtime/gen/gl_thunks.c, one shim per desktop-GL command (core + every "gl" extension). Each shim
reads its Win64 arguments from the guest Ctx (integers/pointers in rcx/rdx/r8/r9, floats in xmm0-3 by
position, the rest on the stack), calls the host function from Apple's OpenGL.framework, and returns the
result in rax (or xmm0 for float returns).

The function types are declared here from gl.xml, not taken from Apple's headers: macOS only ships headers
up to GL 4.1 and splits legacy/core, while the guest may ask for anything. Commands the host lacks resolve
to NULL at runtime: wglGetProcAddress then reports them missing, as a Windows driver would.

Types are the same size on Windows x64 and arm64 macOS except GLhandleARB (Windows: unsigned int, Apple:
void *), which is converted. Commands taking callbacks (debug output) are hand-written in runtime/opengl.c.

Usage: gen_opengl.py <gl.xml>
"""
import os
import re
import sys
import xml.etree.ElementTree as ET

GPR = ["RCX", "RDX", "R8", "R9"]
HAND_WRITTEN = {"glDebugMessageCallback", "glDebugMessageCallbackARB", "glDebugMessageCallbackKHR",
                "glDebugMessageCallbackAMD", "glGetVkProcAddrNV"}  # not on macOS: never exposed
CALLBACK_TYPES = {"GLDEBUGPROC", "GLDEBUGPROCARB", "GLDEBUGPROCKHR", "GLDEBUGPROCAMD", "GLVULKANPROCNV"}

TYPEDEFS = """typedef unsigned int GLenum; typedef unsigned char GLboolean; typedef unsigned int GLbitfield;
typedef void GLvoid; typedef signed char GLbyte; typedef unsigned char GLubyte; typedef short GLshort;
typedef unsigned short GLushort; typedef int GLint; typedef unsigned int GLuint; typedef int GLclampx;
typedef int GLsizei; typedef float GLfloat; typedef float GLclampf; typedef double GLdouble; typedef double GLclampd;
typedef char GLchar; typedef char GLcharARB; typedef unsigned short GLhalf; typedef unsigned short GLhalfARB;
typedef unsigned short GLhalfNV; typedef int GLfixed; typedef long GLintptr; typedef long GLsizeiptr;
typedef long GLintptrARB; typedef long GLsizeiptrARB; typedef long long GLint64; typedef unsigned long long GLuint64;
typedef long long GLint64EXT; typedef unsigned long long GLuint64EXT; typedef struct __GLsync *GLsync;
typedef void *GLeglImageOES; typedef void *GLeglClientBufferEXT; typedef long GLvdpauSurfaceNV;
typedef unsigned int GLhandleARB;   /* the guest's (Windows) view */
struct _cl_context; struct _cl_event;
"""


def main(path):
    root = ET.parse(path).getroot()

    def gl_api(s):
        return s is None or bool(re.search(r"(^|\|)(gl|glcore)(\||$)", s))
    wanted = set()
    for f in root.iter("feature"):
        if f.get("api") == "gl":
            for req in f.iter("require"):
                if req.get("api") in (None, "gl"):
                    wanted.update(c.get("name") for c in req.iter("command"))
    for ext in root.iter("extension"):
        if gl_api(ext.get("supported")) and ext.get("supported") != "disabled":
            for req in ext.iter("require"):
                if req.get("api") in (None, "gl"):
                    wanted.update(c.get("name") for c in req.iter("command"))

    out = ["// GENERATED by tools/gen_opengl.py from gl.xml - do not edit.",
           "#include \"gl_bridge.h\"", "#include <string.h>", "", TYPEDEFS]
    table, skipped = [], []
    for c in root.find("commands"):
        proto = c.find("proto")
        name = proto.find("name").text
        if name not in wanted or name in HAND_WRITTEN:
            continue
        ret_text = "".join(proto.itertext()).rsplit(name, 1)[0].strip()
        ret_type = proto.find("ptype").text if proto.find("ptype") is not None else ret_text.replace("const", "").replace("*", "").strip()
        ret_ptr = "*" in ret_text
        params, bad = [], False
        for p in c.findall("param"):
            pname = p.find("name").text
            text = "".join(p.itertext()).strip()
            pt = p.find("ptype")
            ty = pt.text if pt is not None else re.sub(r"\bconst\b|\*", "", text.rsplit(pname, 1)[0]).strip()
            if ty in CALLBACK_TYPES:
                bad = True
            ptr = "*" in text or "[" in text
            ctype = text.rsplit(pname, 1)[0].strip() + ("*" if "[" in text else "")
            params.append((ty, pname, ptr, ctype))
        if bad or ret_type in CALLBACK_TYPES:
            skipped.append(name)
            continue

        host_params, args = [], []
        for i, (ty, pname, ptr, ctype) in enumerate(params):
            raw_int = f"c->r[{GPR[i]}]" if i < 4 else f"LD64(c->r[RSP] + {8 * (i + 1)})"
            if ptr:
                host_params.append("void *" if ty == "GLhandleARB" else ctype)
                args.append(f"(void *)(uintptr_t){raw_int}")
            elif ty in ("GLfloat", "GLclampf", "GLdouble", "GLclampd"):
                host_params.append(ty)
                if i < 4:
                    args.append(f"c->x[{i}].{'f' if ty in ('GLfloat', 'GLclampf') else 'fd'}[0]")
                else:
                    args.append(f"({{ u64 v_ = {raw_int}; {ty} f_; memcpy(&f_, &v_, sizeof f_); f_; }})")
            elif ty == "GLhandleARB":
                host_params.append("void *")
                args.append(f"(void *)(uintptr_t)(u32){raw_int}")
            else:
                host_params.append(ty)
                args.append(f"({ty}){raw_int}")
        if ret_ptr:
            host_ret = ret_text
        elif ret_type == "GLhandleARB":
            host_ret = "void *"
        else:
            host_ret = ret_text or "void"
        call = f"fn({', '.join(args)})"
        if host_ret == "void":
            body = f"{call};"
        elif ret_type in ("GLfloat", "GLclampf") and not ret_ptr:
            body = f"c->x[0].f[0] = {call};"
        elif ret_type in ("GLdouble", "GLclampd") and not ret_ptr:
            body = f"c->x[0].fd[0] = {call};"
        elif ret_ptr or ret_type == "GLhandleARB":
            body = f"c->r[RAX] = (u64)(uintptr_t){call};" if ret_type != "GLhandleARB" else f"c->r[RAX] = (u32)(uintptr_t){call};"
        else:
            body = f"c->r[RAX] = (u64){call};"
        proto_s = ", ".join(host_params) or "void"
        out.append(f"static void gl_{name}(Ctx *c) {{\n"
                   f"    typedef {host_ret} (*F)({proto_s}); static F fn; static int tried;\n"
                   f"    if (!tried) {{ fn = (F)gl_host_proc(\"{name}\"); tried = 1; }}\n"
                   f"    if (!fn) {{ gl_missing(\"{name}\"); c->r[RAX] = 0; return; }}\n"
                   f"    {body}\n}}")
        table.append(name)
    out.append("\nconst Shim shims_gl_gen[] = {")
    out += [f"    {{ NULL, \"{n}\", gl_{n} }}," for n in table]
    out.append("    { 0, 0, 0 }\n};\n")
    os.makedirs("runtime/gen", exist_ok=True)
    open("runtime/gen/gl_thunks.c", "w").write("\n".join(out))
    print(f"[gen_opengl] {len(table)} thunks, {len(skipped)} callback commands left to runtime/opengl.c: {skipped}")


if __name__ == "__main__":
    main(sys.argv[1])
