#!/usr/bin/env python3
"""Compile the D3D12 test shaders and write them as C arrays (checked in, so `make check` needs neither compiler):
  tests/shaders/sm6x/*.hlsl -> tests/shaders/dx12_sm6x_blobs.h   SM 6.x feature shaders (DXC)            dx12_sm6x.c
  tests/shaders/gs/*.hlsl   -> tests/shaders/dx12_gs_blobs.h     GS / SO / sampler fallbacks, as DXBC
                                                                 (vkd3d-compiler, fxc's role) and DXIL (DXC)  dx12_gs_fallback.c
DXC is Microsoft's DirectXShaderCompiler, built from source for macOS by tools/build_dxc.sh.
Usage: gen_dx12_blobs.py [path/to/dxc]
"""
import os
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SRC = os.path.join(ROOT, "tests", "shaders", "sm6x")
OUT = os.path.join(ROOT, "tests", "shaders", "dx12_sm6x_blobs.h")
GS_SRC = os.path.join(ROOT, "tests", "shaders", "gs")
GS_OUT = os.path.join(ROOT, "tests", "shaders", "dx12_gs_blobs.h")
VKD3D = os.path.join(ROOT, "third_party", "vkd3d", "install")
# name, stage: each is built as <stage>_5_0 DXBC and <stage>_6_0 DXIL
GS_SHADERS = [("vs", "vs"), ("ps", "ps"), ("gs_pass", "gs"), ("gs_expand", "gs"), ("gs_layer", "gs"),
              ("ps_tex", "ps"), ("ps_tex3d", "ps"), ("ps_cube", "ps"), ("ps_buf", "ps"), ("vs_full", "vs"), ("ps_heavy", "ps")]
# name, profile, extra flags
SHADERS = [
    ("wave60", "cs_6_0", []), ("int64", "cs_6_0", []), ("f16", "cs_6_2", ["-enable-16bit-types"]),
    ("dot4", "cs_6_4", ["-enable-16bit-types"]), ("wave65", "cs_6_5", []), ("atomic64", "cs_6_6", []),
    ("dynres", "cs_6_6", []), ("pack66", "cs_6_6", ["-enable-16bit-types"]), ("csderiv", "cs_6_6", []),
    ("rayquery", "cs_6_5", []), ("mesh", "ms_6_5", []), ("bary_vs", "vs_6_1", []), ("bary_ps", "ps_6_1", []),
    ("viewid_vs", "vs_6_1", []), ("wave_vs", "vs_6_0", []), ("quad_ps", "ps_6_0", []),
]


def emit(out, name, data, comment):
    out.append(f"static const unsigned char {name}[{len(data)}] = {{  // {comment}")
    for i in range(0, len(data), 24):
        out.append("    " + "".join(f"0x{b:02x}," for b in data[i:i + 24]))
    out.append("};")


def gs_blobs(dxc, version, tmp):
    vkc = os.path.join(VKD3D, "bin", "vkd3d-compiler")
    env = dict(os.environ, DYLD_LIBRARY_PATH=os.path.join(VKD3D, "lib"))
    out = [f"// Generated by tools/gen_dx12_blobs.py from tests/shaders/gs/*.hlsl: <name>_dxbc by vkd3d-compiler (SM 5.0),",
           f"// <name>_dxil by DXC ({version}, SM 6.0). Do not edit.", "#pragma once", ""]
    for name, stage in GS_SHADERS:
        src = os.path.join(GS_SRC, name + ".hlsl")
        a, b = os.path.join(tmp, name + ".dxbc"), os.path.join(tmp, name + ".dxil")
        subprocess.run([vkc, "-x", "hlsl", "-b", "dxbc-tpf", "-p", f"{stage}_5_0", "-e", "main", "-o", a, src], check=True, env=env)
        subprocess.run([dxc, "-nologo", "-T", f"{stage}_6_0", "-E", "main", "-Fo", b, src], check=True, cwd=GS_SRC)
        emit(out, f"gs_{name}_dxbc", open(a, "rb").read(), f"{stage}_5_0")
        emit(out, f"gs_{name}_dxil", open(b, "rb").read(), f"{stage}_6_0")
    open(GS_OUT, "w").write("\n".join(out) + "\n")
    print(f"[gs] {len(GS_SHADERS)} shaders x2 -> {GS_OUT}")


def main():
    dxc = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "third_party", "dxc", "build", "bin", "dxc")
    version = subprocess.run([dxc, "--version"], capture_output=True, text=True).stdout.strip()
    out = [f"// Generated by tools/gen_dx12_blobs.py from tests/shaders/sm6x/*.hlsl with DXC ({version}). Do not edit.",
           "// DXIL containers for tests/src/dx12_sm6x.c.", "#pragma once", ""]
    with tempfile.TemporaryDirectory() as tmp:
        for name, profile, flags in SHADERS:
            dst = os.path.join(tmp, name + ".dxil")
            subprocess.run([dxc, "-nologo", "-T", profile, "-E", "main", *flags, "-Fo", dst, os.path.join(SRC, name + ".hlsl")],
                           check=True, cwd=SRC)
            emit(out, f"sm6x_{name}", open(dst, "rb").read(), f"{profile} {' '.join(flags)}".strip())
        gs_blobs(dxc, version, tmp)
    open(OUT, "w").write("\n".join(out) + "\n")
    print(f"[sm6x] {len(SHADERS)} shaders -> {OUT}")


if __name__ == "__main__":
    main()
