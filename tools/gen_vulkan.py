#!/usr/bin/env python3
"""Generate Win64-ABI -> host Vulkan thunks from the Khronos registry (vk.xml).

Outputs:
  runtime/gen/vulkan_thunks.c  one shim per Vulkan command: reads Win64 args from the guest Ctx, calls the
                               host (MoltenVK via the Vulkan loader) and returns the result in rax.
  tools/vulkan-1.def           export list used to build a mingw import library for test programs.

Why this works without struct translation: Vulkan structs only use fixed-width types, pointers, enums and
size_t. Those have the same size and alignment on Windows x64 and arm64 macOS, and guest memory is
identity mapped, so guest structs are passed to the host as-is.

Usage: gen_vulkan.py <vk.xml>
"""
import os
import sys
import xml.etree.ElementTree as ET

HAND_WRITTEN = {  # implemented in runtime/vulkan.c
    "vkGetInstanceProcAddr", "vkGetDeviceProcAddr", "vkCreateInstance", "vkDestroyInstance",
    "vkEnumerateInstanceExtensionProperties", "vkCreateDevice", "vkCreateWin32SurfaceKHR",
    "vkGetPhysicalDeviceWin32PresentationSupportKHR", "vkCreateDebugUtilsMessengerEXT",
    "vkDestroyDebugUtilsMessengerEXT", "vkCreateDebugReportCallbackEXT", "vkDestroyDebugReportCallbackEXT",
    "vkEnumerateDeviceExtensionProperties",
}
FLOATS = {"float": "f", "double": "fd"}
GPR = ["RCX", "RDX", "R8", "R9"]


def main(path):
    root = ET.parse(path).getroot()
    # struct/union type names (to detect by-value aggregate params)
    aggregates = {t.get("name") for t in root.iter("type") if t.get("category") in ("struct", "union")}
    # A command is generated only if desktop Vulkan actually defines it: required by a "vulkan" feature, or
    # by an extension supported on "vulkan" that isn't platform-specific (win32, xlib, ...) or provisional.
    def api_ok(el, attr="api"):
        v = el.get(attr)
        return v is None or "vulkan" in v.split(",")
    core, ext_ok, platform_only = set(), set(), set()
    for f in root.iter("feature"):
        if not api_ok(f):
            continue
        for req in f.iter("require"):
            if api_ok(req):
                core.update(c.get("name") for c in req.iter("command"))
    for ext in root.iter("extension"):
        if not api_ok(ext, "supported"):
            continue
        plat = ext.get("platform") or ext.get("provisional") == "true"
        for req in ext.iter("require"):
            if not api_ok(req):
                continue
            for c in req.iter("command"):
                (platform_only if plat else ext_ok).add(c.get("name"))
    wanted = core | ext_ok
    platform_only -= wanted
    disabled_only = set()

    cmds, aliases = {}, {}
    for c in root.find("commands"):
        if c.get("api") and "vulkan" not in c.get("api").split(","):
            continue
        if c.get("alias"):
            aliases[c.get("name")] = c.get("alias")
            continue
        proto = c.find("proto")
        name = proto.find("name").text
        ret = "".join(proto.itertext()).replace(name, "").strip()
        params = []
        for p in c.findall("param"):
            if p.get("api") and "vulkan" not in p.get("api").split(","):
                continue
            text = "".join(p.itertext()).strip()
            ty = p.find("type").text
            pname = p.find("name").text
            ptr = "*" in text or "[" in text
            params.append((ty, pname, ptr, text))
        cmds[name] = (ret, params)

    gen, skipped, byval = [], [], []
    out = ["// GENERATED by tools/gen_vulkan.py from vk.xml - do not edit.",
           "#define VK_USE_PLATFORM_METAL_EXT 1", "#include <vulkan/vulkan.h>", "#include \"vk_bridge.h\"", ""]
    table = []
    names = sorted(set(cmds) | set(aliases))
    for name in names:
        base = aliases.get(name, name)
        if name in HAND_WRITTEN or base not in cmds:
            continue
        if name not in wanted:
            skipped.append(name)
            continue
        ret, params = cmds[base]
        args = []
        bad = False
        for i, (ty, pname, ptr, text) in enumerate(params):
            if i < 4:
                raw_int = f"c->r[{GPR[i]}]"
                raw_flt = f"c->x[{i}]"
            else:
                raw_int = f"LD64(c->r[RSP] + {8 * (i + 1)})"
                raw_flt = None
            if ptr:
                if ty == "VkAllocationCallbacks":
                    args.append("NULL /* guest allocators ignored */")
                else:
                    cast = text.split(pname)[0].strip() + " *" if "[" in text else _ptr_type(text, pname)
                    args.append(f"({cast})(uintptr_t){raw_int}")
            elif ty in FLOATS:
                if raw_flt:
                    args.append(f"{raw_flt}.{FLOATS[ty]}[0]")
                else:
                    args.append(f"({{ u64 v_ = {raw_int}; {ty} f_; memcpy(&f_, &v_, sizeof f_); f_; }})")
            elif ty in aggregates:
                # Win64 passes aggregates > 8 bytes by hidden pointer
                byval.append(name)
                args.append(f"*({ty} *)(uintptr_t){raw_int}")
            else:
                args.append(f"({ty}){raw_int}")
        if bad:
            continue
        pfn = f"PFN_{base}"
        call = f"fn({', '.join(args)})"
        body = f"{call};" if ret == "void" else f"c->r[RAX] = (u64)(uintptr_t){call};"
        out.append(f"static void vk_{name}(Ctx *c) {{\n"
                   f"    static {pfn} fn; static unsigned gen;\n"
                   f"    if (gen != vk_generation || !fn) {{ fn = ({pfn})vk_host_proc(\"{name}\"); gen = vk_generation; }}\n"
                   f"    if (!fn) {{ vk_missing(\"{name}\"); c->r[RAX] = (u64)(i64)VK_ERROR_EXTENSION_NOT_PRESENT; return; }}\n"
                   f"    {body}\n}}")
        table.append(name)
        gen.append(name)
    out.append("\nconst Shim shims_vulkan_gen[] = {")
    out += [f"    {{ NULL, \"{n}\", vk_{n} }}," for n in table]
    out.append("    { 0, 0, 0 }\n};\n")
    os.makedirs("runtime/gen", exist_ok=True)
    open("runtime/gen/vulkan_thunks.c", "w").write("\n".join(out))

    core_names = sorted(n for n in set(cmds) | set(aliases) if n in core or aliases.get(n) in core
                        or n in ("vkCreateWin32SurfaceKHR", "vkGetPhysicalDeviceWin32PresentationSupportKHR",
                                 "vkDestroySurfaceKHR", "vkGetPhysicalDeviceSurfaceSupportKHR",
                                 "vkGetPhysicalDeviceSurfaceCapabilitiesKHR", "vkGetPhysicalDeviceSurfaceFormatsKHR",
                                 "vkGetPhysicalDeviceSurfacePresentModesKHR", "vkCreateSwapchainKHR",
                                 "vkDestroySwapchainKHR", "vkGetSwapchainImagesKHR", "vkAcquireNextImageKHR",
                                 "vkQueuePresentKHR"))
    open("tools/vulkan-1.def", "w").write("LIBRARY vulkan-1.dll\nEXPORTS\n" + "".join(f"    {n}\n" for n in core_names))
    print(f"[gen_vulkan] {len(gen)} thunks, {len(skipped)} platform-only skipped, "
          f"{len(set(byval))} by-value aggregate commands: {sorted(set(byval))[:8]}")


def _ptr_type(text, pname):
    t = text.rsplit(pname, 1)[0].strip()
    return t


if __name__ == "__main__":
    main(sys.argv[1])
